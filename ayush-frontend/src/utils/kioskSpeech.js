/**
 * Resolves a prompt to `{ text, code }` that ALWAYS agree: if a language has no
 * translation for this prompt we speak the English line under `en-IN` rather than
 * feeding one language's text to another language's voice.
 */
export function speechFor(langCode, key) {
  const code = normalizeLang(langCode);
  const table = KIOSK_PROMPTS[key] || {};
  if (table[code]) return { text: table[code], code };
  return { text: table['en-IN'] || '', code: 'en-IN' };
}
